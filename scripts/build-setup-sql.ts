/**
 * Build supabase/setup.sql: every migration in one transaction, for pasting
 * into the Supabase SQL Editor on a NEW project (no CLI or database password
 * needed on your machine).
 *
 *   pnpm db:setup-sql
 *
 * It records each migration in app_meta.schema_migrations, so `pnpm db:migrate`
 * later applies only newer migrations. Running it twice fails harmlessly on
 * the first "already exists" error and changes nothing (single transaction).
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const DIR = path.join(process.cwd(), "supabase", "migrations");
const OUT = path.join(process.cwd(), "supabase", "setup.sql");

async function main() {
  const files = (await readdir(DIR)).filter((f) => f.endsWith(".sql")).sort();
  const parts = [
    "-- Poker Bankroll Pro: one-time database setup for a new Supabase project.",
    "-- GENERATED by `pnpm db:setup-sql` from supabase/migrations. Do not edit by hand.",
    "-- Paste the whole file into Supabase > SQL Editor > New query, then Run.",
    "",
    "begin;",
    "",
    "create schema if not exists app_meta;",
    "revoke all on schema app_meta from public;",
    "create table if not exists app_meta.schema_migrations (version text primary key, applied_at timestamptz not null default now());",
    "",
  ];
  for (const f of files) {
    parts.push(`-- ===== ${f} =====`, (await readFile(path.join(DIR, f), "utf8")).trim(), `insert into app_meta.schema_migrations (version) values ('${f}');`, "");
  }
  parts.push(
    "-- Private bucket for receipts and attachments (served only through the app).",
    "do $$ begin",
    "  if exists (select 1 from information_schema.columns where table_schema = 'storage' and table_name = 'buckets' and column_name = 'public') then",
    "    insert into storage.buckets (id, name, public) values ('attachments', 'attachments', false) on conflict (id) do nothing;",
    "  else",
    "    raise notice 'Storage is not set up in this database; create a private bucket named attachments in the dashboard.';",
    "  end if;",
    "end $$;",
    "",
    "commit;",
    "",
  );
  await writeFile(OUT, parts.join("\n"));
  console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${files.length} migrations)`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
